// build-single.js
// Builds dist/gym-app.html: the whole app in one file that runs when opened from disk (file://) in a
// desktop browser. esbuild bundles js/app.js and its imports into one script; the four stylesheets
// are inlined with the fonts as base64 data URLs; every data/**/*.json file is inlined as
// <script type="application/json" id="data-NAME"> for loadData(); GSAP is inlined as a classic
// script. "</script" in inlined text is escaped. No service worker in this build (app.js skips it).
// Usage: npm install, then `node build-single.js`.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = f => readFileSync(join(root, f), 'utf8');

// JS and CSS: stop an inlined "</script" or "</style" from closing the element early.
const escapeTag = (s, tag) => s.replace(new RegExp(`</(${tag})`, 'gi'), '<\\/$1');
// JSON: escaping every "<" keeps the JSON valid and cannot close the script element.
const escapeJson = s => s.replace(/</g, '\\u003c');

const js = (await build({
  entryPoints: [join(root, 'js/app.js')], bundle: true, format: 'iife', minify: true, write: false,
  target: ['chrome100', 'firefox100', 'safari15'], legalComments: 'none',
})).outputFiles[0].text;

const fontData = f => `data:font/woff2;base64,${readFileSync(join(root, 'fonts', f)).toString('base64')}`;
const css = ['tokens', 'base', 'components', 'animations'].map(n => read(`css/${n}.css`)).join('\n')
  .replace(/url\(["']?\.\.\/fonts\/([^"')]+)["']?\)/g, (_, f) => `url("${fontData(f)}")`);
if (/\.\.\/fonts\//.test(css)) throw new Error('a font URL was not inlined');

const walk = dir => readdirSync(join(root, dir)).flatMap(f => {
  const p = join(dir, f);
  return statSync(join(root, p)).isDirectory() ? walk(p) : [p];
});
const data = walk('data').filter(f => f.endsWith('.json')).sort().map(f => {
  const name = relative('data', f).split(sep).join('/').replace(/\.json$/, '');
  return `<script type="application/json" id="data-${name}">${escapeJson(JSON.stringify(JSON.parse(read(f))))}</script>`;
});

const icon = `data:image/svg+xml;base64,${Buffer.from(read('icons/icon.svg')).toString('base64')}`;
const gsap = read('vendor/gsap.min.js');

// Shell from index.html: keep the head meta and body; replace stylesheet links and scripts.
const shell = read('index.html')
  .replace(/<!--[\s\S]*?-->\s*/, '')
  .replace(/\s*<link rel="(stylesheet|manifest|apple-touch-icon)"[^>]*>/g, '')
  .replace(/<link rel="icon"[^>]*>/, () => `<link rel="icon" href="${icon}" type="image/svg+xml">`)
  .replace(/\s*<script[^>]*><\/script>/g, '');

// Function replacers: inlined code contains "$&" and "$1", which a replacement *string* would expand.
const html = shell
  .replace('</head>', () => `  <style>\n${escapeTag(css, 'style')}\n</style>\n</head>`)
  .replace('</body>', () => `${data.join('\n')}\n<script>${escapeTag(gsap, 'script')}</script>\n<script>${escapeTag(js, 'script')}</script>\n</body>`)
  .replace('<!doctype html>', () => '<!doctype html>\n<!-- gym-app.html: single-file build of Gym Plan (generated by build-single.js; do not edit). Opens from disk in a desktop browser. -->');
if (!html.includes(js.slice(-200)) || !html.includes(gsap.slice(0, 200))) throw new Error('inlined script was altered');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/gym-app.html'), html);
console.log(`dist/gym-app.html: ${(html.length / 1024).toFixed(0)} KB, ${data.length} data files inlined`);
