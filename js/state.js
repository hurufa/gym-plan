// state.js
// All persistent user data: one localStorage key holding a versioned object.
// Exposes load/save, schema migration, local-date helpers, record CRUD, and export/import
// (validate -> preview -> replace or merge). Views read `getState()` and write through `update()`.

export const STORAGE_KEY = 'gym-app';
export const SCHEMA_VERSION = 1;

// Collections of records; every record has `id` (uuid) and `updatedAt` (ms timestamp).
export const COLLECTIONS = ['workouts', 'bodyweights', 'measurements', 'meals', 'notes', 'swaps', 'deloads'];

export function defaultState() {
  return {
    schemaVersion: SCHEMA_VERSION,
    profile: null,           // set by onboarding; see js/views/onboarding.js for fields
    settings: { lang: null, theme: 'system', sound: true, vibration: true, updatedAt: 0 },
    plan: null,              // generated by planner.js (phase 4)
    activeSession: null,     // in-progress workout (phase 6)
    nutritionAck: false,
    nutrition: null,         // nutrition preferences (slider, filters, swaps); see nutrition.js defaultPrefs
    lastExportAt: null,
    createdAt: Date.now(),
    ...Object.fromEntries(COLLECTIONS.map(c => [c, []])),
  };
}

// Migration: each step takes version n and returns version n+1.
// Version 0 = anything saved before schemaVersion existed (flat profile, no collections).
const MIGRATIONS = {
  0: s => {
    const base = defaultState();
    return { ...base, ...s, settings: { ...base.settings, ...(s.settings || {}) }, schemaVersion: 1 };
  },
};

export function migrate(raw) {
  let s = raw && typeof raw === 'object' ? { ...raw } : defaultState();
  let v = Number.isInteger(s.schemaVersion) ? s.schemaVersion : 0;
  if (v > SCHEMA_VERSION) throw new Error(`Data is from a newer app version (schema ${v}).`);
  while (v < SCHEMA_VERSION) { s = MIGRATIONS[v](s); v = s.schemaVersion; }
  for (const c of COLLECTIONS) if (!Array.isArray(s[c])) s[c] = [];
  return s;
}

let state = null;
const listeners = new Set();
let store = globalThis.localStorage;
// Tests swap in an in-memory storage so they never touch the real data.
export function useStorage(s) { store = s; state = null; }

export function load(storage = store) {
  let raw = null;
  try { raw = JSON.parse(storage.getItem(STORAGE_KEY)); } catch { raw = null; }
  state = raw ? migrate(raw) : defaultState();
  return state;
}

export function save(storage = store) {
  storage.setItem(STORAGE_KEY, JSON.stringify(state));
}

export const getState = () => state ?? load();

// update(fn): mutate a draft, then persist and notify. Returns the new state.
export function update(fn) {
  const s = getState();
  fn(s);
  save();
  listeners.forEach(l => l(s));
  return s;
}
export const subscribe = fn => (listeners.add(fn), () => listeners.delete(fn));

export function replaceState(next) {
  state = migrate(next);
  save();
  listeners.forEach(l => l(state));
  return state;
}

export function clearAll(storage = store) {
  storage.removeItem(STORAGE_KEY);
  state = defaultState();
  listeners.forEach(l => l(state));
}

// ---- ids and dates ----

export function uuid() {
  if (globalThis.crypto?.randomUUID) return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40; b[8] = (b[8] & 0x3f) | 0x80;
  const h = [...b].map(x => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

// Local calendar date as YYYY-MM-DD, built from local parts. Never toISOString(): that is UTC and
// would put a 06:00 session in UTC+7 on the previous day.
export function localDate(d = new Date()) {
  const p = n => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}
export function parseLocalDate(s) {
  const [y, m, d] = s.split('-').map(Number);
  return new Date(y, m - 1, d);
}

// ---- records ----

export function upsertRecord(collection, record) {
  const rec = { ...record, id: record.id || uuid(), updatedAt: Date.now() };
  update(s => {
    const i = s[collection].findIndex(r => r.id === rec.id);
    if (i >= 0) s[collection][i] = rec; else s[collection].push(rec);
  });
  return rec;
}
export function deleteRecord(collection, id) {
  update(s => { s[collection] = s[collection].filter(r => r.id !== id); });
}

// ---- export / import ----

export function exportFileName(d = new Date()) { return `gym-data-${localDate(d)}.json`; }

export function exportData(s = getState()) {
  return JSON.stringify({ app: 'gym-app', exportedAt: Date.now(), data: s }, null, 2);
}

// Validates an export file's text. Returns { ok, data, errors }.
export function validateImport(text) {
  const errors = [];
  let parsed;
  try { parsed = JSON.parse(text); } catch { return { ok: false, errors: ['notJson'] }; }
  if (!parsed || parsed.app !== 'gym-app' || typeof parsed.data !== 'object' || parsed.data === null) {
    return { ok: false, errors: ['notExport'] };
  }
  let data;
  try { data = migrate(parsed.data); } catch { return { ok: false, errors: ['newerVersion'] }; }
  for (const c of COLLECTIONS) {
    for (const r of data[c]) {
      if (!r || typeof r.id !== 'string' || typeof r.updatedAt !== 'number') { errors.push(`badRecord:${c}`); break; }
    }
  }
  return { ok: errors.length === 0, data, errors };
}

// Merge rule: match records by id, newer updatedAt wins. Profile, settings and nutrition preferences:
// newer updatedAt wins.
export function mergeStates(current, incoming) {
  const out = structuredClone(current);
  for (const c of COLLECTIONS) {
    const byId = new Map(out[c].map(r => [r.id, r]));
    for (const r of incoming[c]) {
      const mine = byId.get(r.id);
      if (!mine || r.updatedAt > mine.updatedAt) byId.set(r.id, r);
    }
    out[c] = [...byId.values()];
  }
  for (const k of ['profile', 'settings', 'nutrition']) {
    if (incoming[k] && (!out[k] || (incoming[k].updatedAt || 0) > (out[k].updatedAt || 0))) out[k] = incoming[k];
  }
  if (incoming.plan && (!out.plan || (incoming.plan.updatedAt || 0) > (out.plan.updatedAt || 0))) out.plan = incoming.plan;
  out.lastExportAt = Math.max(out.lastExportAt || 0, incoming.lastExportAt || 0) || null;
  out.nutritionAck = out.nutritionAck || incoming.nutritionAck;
  return out;
}

// What an import would change, per collection: counts of added / updated / unchanged / removed.
export function previewImport(current, incoming, mode) {
  const rows = COLLECTIONS.map(c => {
    const mine = new Map(current[c].map(r => [r.id, r]));
    const theirs = new Map(incoming[c].map(r => [r.id, r]));
    let added = 0, updated = 0, unchanged = 0, removed = 0;
    for (const [id, r] of theirs) {
      const m = mine.get(id);
      if (!m) added++;
      else if (mode === 'replace' ? JSON.stringify(m) !== JSON.stringify(r) : r.updatedAt > m.updatedAt) updated++;
      else unchanged++;
    }
    if (mode === 'replace') for (const id of mine.keys()) if (!theirs.has(id)) removed++;
    return { collection: c, added, updated, unchanged, removed };
  });
  return {
    rows,
    profileChanges: JSON.stringify(current.profile) !== JSON.stringify(incoming.profile) &&
      (mode === 'replace' || (incoming.profile?.updatedAt || 0) > (current.profile?.updatedAt || 0)),
  };
}

export function applyImport(incoming, mode) {
  return replaceState(mode === 'replace' ? incoming : mergeStates(getState(), incoming));
}
